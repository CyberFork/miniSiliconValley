import assert from 'node:assert/strict';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
import {buildStudentWorkbook} from '../scripts/prompt-packs.mjs';
const root=resolve(import.meta.dirname,'..'),source=resolve(root,'../../prompts/game-development');
const prompt=await readFile(join(source,'student-prompt.txt'),'utf8');
for(const term of ['主棍＋模块地图','子棍＋模块描述','执行者→上下文与项目设计→目标→约束→避免→验收','每次只展示一个模块','未确认前，不要派生子棍','不写游戏代码','完整文档交付后就停止','基于立棍方法的开发文档','不要把一条操作路线直接当成整个模块地图'])assert(prompt.includes(term),term);
// Check the actual progress block, not unrelated mentions elsewhere in the prompt.
const progress=prompt.split('【进度提示】')[1]?.split('【先问清楚，再整理主棍】')[0];
assert(progress,'progress instructions must be present');
for(const term of ['主棍：已明确 n/6 项','子棍：正在核对第 n 个模块，共 m 个（n/m）','n 是当前模块序号，不是已确认数量','不显示子棍内部六项进度','等待我确认'])assert(progress.includes(term),term);
assert.match(progress,/每次回复开头只显示当前阶段的一行进度/);
assert.match(progress,/确认后才推进到下一个/);
assert.match(progress,/修改当前模块时不推进/);
assert.match(progress,/增删或调整模块.*说明变化.*更新总数 m/);
assert.match(progress,/不按提问次数统计/);
assert.match(progress,/达到 6\/6.*等待你确认/);
const choices=prompt.split('【遇到决策，先给选择】')[1]?.split('【进度提示】')[0];
assert(choices,'decision guidance must be explicit');
for(const term of ['同时用于补全主棍和核对子棍','2–3 个','不要等我说“不知道”','每次仍只讨论一个决策','推荐','为什么适合','自己的想法','待决定','不能默认采用推荐','事实信息','遵守主棍','完整模块方案'])assert(choices.includes(term),term);
const delivery=prompt.split('【最后输出完整开发文档】')[1];
// Basics must be asked before master approval, not merely mentioned in handoff.
const interview=prompt.split('【先问清楚，再整理主棍】')[1]?.split('【根据主棍，逐个核对子棍】')[0];
assert(interview,'master interview must be present');
for(const term of ['游戏基础也必须纳入主棍问答','电脑、平板还是手机','在浏览器里玩','下载安装式 APP','运行设备和打开方式分开判断','手机也能玩网页游戏','Android／iOS','2D（','3D（','像素风是美术风格，不等于 2D','Minecraft 也不代表','键盘／鼠标','触屏点击','横屏／竖屏','不同设备联网玩','是否保留进度','不默加账号','不要求学生选择引擎','已写明的要求直接归纳','不能计为已明确','不能显示“主棍：已明确 6/6 项”','不增加第七项或额外进度','最终只能给待确认草稿'])assert(interview.includes(term),term);
assert(interview.includes('不要一次把整张问卷丢给我'));
assert(interview.includes('每次只问一个主要问题'));
for(const term of ['先承接产品课已经完成的材料','界面截图、手绘稿、可点击原型、原型链接或 HTML 文件','已给策划就不再索要策划','已给 UI 就不再索要 UI','暂不提供／以后补充','不反复催交','不具有上传或读图能力','不能假装看过','已读取／已收到但无法读取／尚未提供','标明文件名、页面名或链接','不把截图或可点击原型当成业务功能已实现','策划与 UI 冲突','缺少原始文件本身不阻止主棍确认或文档完成'])assert(interview.includes(term),term);
const moduleReview=prompt.split('【根据主棍，逐个核对子棍】')[1]?.split('【最后输出完整开发文档】')[0];
assert(moduleReview.includes('继承已确认的基础选择'));
assert(moduleReview.includes('先让我确认主棍变更'));
assert(moduleReview.includes('重新确认受影响子棍'));
for(const term of ['界面／UI 责任明确放进模块地图','一页 UI 不等于一个功能模块','玩家操作 → 功能模块处理 → 返回状态 → UI 更新','不自己再维护另一套物品真值','引用具体页面／组件','不能编造原图内容','后续补充策划或 UI','保留未受影响的确认结果'])assert(moduleReview.includes(term),term);
assert(delivery.includes('运行设备、打开方式、2D／3D 与视角、操作方式等已确认基础必须写进文档'));
for(const term of ['策划与 UI 的来源、实际采用的内容','明确 UI 与功能模块的对应、交接和验收','不只丢一个外链','不能假设另一个 AI 已拥有本次附件'])assert(delivery.includes(term),term);
for(const term of ['同一个 Markdown 代码框','```markdown','标题、主棍、模块地图、全部子棍、检查方法和开发交接说明','不要拆成多个代码框','不要在框内嵌套','不代表要输出游戏程序代码'])assert(delivery.includes(term),term);
assert(!/Skill|①|②|③|依赖|校园寻宝|\|---/.test(prompt));
const html=await readFile(join(source,'index.html'),'utf8');
assert.equal((html.match(/<button\b/g)||[]).length,1);
assert(html.includes('本页不上传附件'));
assert(html.includes('暂时不提供也能继续'));
assert(!/catalog\.js|copy-skill|download|<select|Skill|①|②|③|依赖/.test(html));
const temp=await mkdtemp(join(tmpdir(),'msv-simple-'));
try{
 const manifest=await buildStudentWorkbook(source,temp),context={window:{}};
 vm.runInNewContext(await readFile(join(temp,'student-prompt.js'),'utf8'),context);
 assert.equal(context.window.MSV_STUDENT_PROMPT,prompt);
 for(const [file,hash] of Object.entries(manifest.files))assert.equal(createHash('sha256').update(await readFile(join(temp,file))).digest('hex'),hash);
 const conf=await readFile(resolve(root,'../../deploy/minisv/gateway/default.conf'),'utf8');
 for(const file of Object.keys(manifest.files))assert(conf.includes(`/r24/audience/ai-materials/workbook/${file} /courseware-maintenance/p1-workbook-r24/${file};`));
 assert(conf.includes('location ^~ /courseware-maintenance/ { internal; }'));
 assert(conf.split('location ^~ /courseware/development-mentor-module-thinking/r24/ {')[1].split('}')[0].includes('auth_request /_minisv_courseware_auth;'));
 console.log('PASS student prompt: macro/micro, six fields, human gates, plan-only stop, one-button UI, generated bytes, protected r24 maintenance routes');
}finally{await rm(temp,{recursive:true,force:true});}
