/**
 * Builds a chapter without weakening the truth boundary. Historical cards must
 * carry source IDs; every other card is stamped as a classroom simulation and
 * receives no source ID. The holder is only a private information seat used for
 * random dealing, never a fixed learner P/D/M/O assignment.
 */
function makeElemeSimulationChapter(seed: ElemeSimulationChapterSeed): ClassroomChapter {
  const identities = seed.identities.map<CaseIdentity>((identity, index) => ({
    ...identity,
    id: `${seed.id}-seat-${index + 1}`,
    nature: "composite",
  }));
  const infoCards = seed.cards.map<ClassroomInfoCard>((card, index) => ({
    id: `${seed.id}-card-${String(index + 1).padStart(2, "0")}`,
    holderIdentityId: identities[card.holder].id,
    kind: card.kind ?? (card.boundary === "historical" ? "fact" : "observation"),
    title: `${card.boundary === "historical" ? "F" : "R"}-${String(index + 1).padStart(2, "0")} · ${card.title}`,
    body: card.boundary === "historical"
      ? `历史边界事实：${card.body}`
      : `课堂模拟（玩家平行世界，不是饿了么史实）：${card.body}`,
    sourceIds: card.boundary === "historical" ? card.sourceIds : [],
    credibility: card.credibility ?? (card.boundary === "historical" ? "high" : "medium"),
    sharePrompt: card.sharePrompt,
  }));
  const { cards: _cards, ...chapter } = seed;
  void _cards;
  return {
    ...chapter,
    identities,
    infoCards,
    intelGate: {
      requiredSourceBackedEvidence: 2,
      requireUserOrPerson: true,
      requireSceneLoss: true,
      requireConstraint: true,
      requireContradictionOrGap: true,
      requireLeadSupportLink: true,
    },
  };
}

